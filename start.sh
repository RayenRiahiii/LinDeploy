#!/usr/bin/env bash
set -e

HOST_IP=""
FRONTEND_PORT="${FRONTEND_PORT:-5173}"
BACKEND_PORT="${BACKEND_PORT:-8000}"
REDIS_PORT="${REDIS_PORT:-6379}"
NO_BUILD=false

while [[ "$#" -gt 0 ]]; do
    case $1 in
        --ip) HOST_IP="$2"; shift ;;
        --frontend-port) FRONTEND_PORT="$2"; shift ;;
        --backend-port) BACKEND_PORT="$2"; shift ;;
        --no-build) NO_BUILD=true ;;
        -h|--help)
            echo "Usage: ./start.sh [--ip <IP>] [--frontend-port <port>] [--backend-port <port>] [--no-build]"
            exit 0
            ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
    shift
done

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "=========================================================="
echo "             LinDeploy Container Launcher                 "
echo "=========================================================="

# 0. Docker Daemon Verification
echo "[0/5] Checking Docker daemon status..."
if ! command -v docker >/dev/null 2>&1; then
    echo "[ERROR] Docker CLI not found. Please install Docker and ensure it is in your PATH." >&2
    exit 1
fi

if ! docker info >/dev/null 2>&1; then
    echo "      Docker daemon is not responding. Attempting to start service..."
    if command -v systemctl >/dev/null 2>&1 && [ "$(id -u)" -eq 0 ]; then
        systemctl start docker || true
    fi
fi

if ! docker info >/dev/null 2>&1; then
    echo "[ERROR] Unable to connect to Docker daemon. Please ensure Docker is running." >&2
    exit 1
fi
echo "      Docker daemon is active and healthy."

# 1. IP Detection
if [ -n "$HOST_IP" ]; then
    DETECTED_IP="$HOST_IP"
    echo "[1/5] Using specified host IP: $DETECTED_IP"
else
    echo "[1/5] Detecting active host LAN IP..."
    DETECTED_IP="127.0.0.1"

    if command -v ip >/dev/null 2>&1; then
        DETECTED_IP=$(ip route get 1.1.1.1 2>/dev/null | awk '{print $7}' | tr -d '\n')
    fi

    if [ -z "$DETECTED_IP" ] && command -v hostname >/dev/null 2>&1; then
        DETECTED_IP=$(hostname -I 2>/dev/null | awk '{print $1}' | tr -d '\n')
    fi

    if [ -z "$DETECTED_IP" ] || [ "$DETECTED_IP" = "127.0.0.1" ]; then
        DETECTED_IP="127.0.0.1"
    fi
    echo "      Detected IP: $DETECTED_IP"
fi

# 2. Database Volume Seeding
echo "[2/5] Checking persistent database volume..."
mkdir -p "$PROJECT_ROOT/data"
if [ ! -f "$PROJECT_ROOT/data/db.sqlite3" ] && [ -f "$PROJECT_ROOT/backend/db.sqlite3" ]; then
    echo "      Seeding existing SQLite database to data/db.sqlite3..."
    cp "$PROJECT_ROOT/backend/db.sqlite3" "$PROJECT_ROOT/data/db.sqlite3"
fi
mkdir -p "$PROJECT_ROOT/infra/mirror/runtime/manifests"

# 3. Mirror TLS Certificates
echo "[3/5] Verifying mirror TLS certificates for $DETECTED_IP..."
MIRROR_CERT="$PROJECT_ROOT/infra/mirror/runtime/certs/mirror.crt"
NEED_CERT_REGEN=true

if [ -f "$MIRROR_CERT" ] && command -v openssl >/dev/null 2>&1; then
    if openssl x509 -in "$MIRROR_CERT" -noout -text 2>/dev/null | grep -q "$DETECTED_IP"; then
        NEED_CERT_REGEN=false
        echo "      Certificates already valid for $DETECTED_IP."
    fi
fi

if [ "$NEED_CERT_REGEN" = true ]; then
    echo "      Generating TLS certificates for IP $DETECTED_IP..."
    chmod +x "$PROJECT_ROOT/infra/mirror/setup.sh" 2>/dev/null || true
    bash "$PROJECT_ROOT/infra/mirror/setup.sh" "$DETECTED_IP"
fi

# 4. Generate .env.docker
echo "[4/5] Updating .env.docker configuration..."
EXISTING_SECRET_KEY=""
if [ -f "$PROJECT_ROOT/.env.docker" ]; then
    EXISTING_SECRET_KEY=$(grep '^DJANGO_SECRET_KEY=' "$PROJECT_ROOT/.env.docker" | cut -d'=' -f2- | tr -d '\r\n')
fi
if [ -z "$EXISTING_SECRET_KEY" ]; then
    EXISTING_SECRET_KEY=$(head -c 40 /dev/urandom | base64 | tr -dc 'A-Za-z0-9_-' | head -c 50)
fi

cat <<EOF > "$PROJECT_ROOT/.env.docker"
# Auto-generated by start.sh on $(date)
LINDEPLOY_HOST_IP=$DETECTED_IP
FRONTEND_PORT=$FRONTEND_PORT
BACKEND_PORT=$BACKEND_PORT
REDIS_PORT=$REDIS_PORT
DJANGO_SECRET_KEY=$EXISTING_SECRET_KEY
DJANGO_DEBUG=False
DJANGO_ALLOWED_HOSTS=*
DJANGO_TIME_ZONE=UTC
LINDEPLOY_MIRROR_ENABLED=True
EOF

# 5. Launch Docker Compose
echo "[5/5] Starting Docker Compose services..."
BUILD_FLAG="--build"
if [ "$NO_BUILD" = true ]; then
    BUILD_FLAG=""
fi

docker compose --env-file "$PROJECT_ROOT/.env.docker" up -d $BUILD_FLAG

echo ""
echo "=========================================================="
echo "           LinDeploy is Running Successfully!             "
echo "=========================================================="
echo "  Web Dashboard:     http://localhost:$FRONTEND_PORT"
if [ "$DETECTED_IP" != "127.0.0.1" ]; then
    echo "  LAN Dashboard:     http://${DETECTED_IP}:$FRONTEND_PORT"
fi
echo "  Backend API:       http://localhost:$BACKEND_PORT/api/"
echo "  Mirror Gateway:    https://${DETECTED_IP}:8443/cache/"
echo "  Ansible Engine:    Native Linux container"
echo ""
echo "To stop all services run:  ./stop.sh"
echo "To view real-time logs:    docker compose logs -f"

