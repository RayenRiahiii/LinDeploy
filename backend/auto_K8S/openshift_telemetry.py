"""
OpenShift SNO Telemetry Poller for LinDeploy.

Queries the Assisted Installer Agent REST API running on port 8090 of the target node
to extract real-time stage breakdowns (e.g. disk write percentage, bootkube initialization,
control plane convergence) and push updates to the active Celery task and Installation model.
"""

import json
import logging
import re
import threading
import time
import urllib.request
import urllib.error

logger = logging.getLogger(__name__)


def extract_openshift_user_token(assets_directory):
    """
    Extract the ephemeral UserAuthToken from .openshift_install_state.json
    generated by openshift-install in the cluster asset directory.
    """
    from pathlib import Path
    state_file = Path(assets_directory) / ".openshift_install_state.json"
    if not state_file.is_file():
        return None

    try:
        data = json.loads(state_file.read_text(encoding="utf-8"))
        auth_config = data.get("*gencrypto.AuthConfig", {})
        return auth_config.get("UserAuthToken")
    except Exception as exc:
        logger.debug("Failed to parse .openshift_install_state.json: %s", exc)
        return None


def fetch_assisted_installer_cluster_telemetry(vm_ip, token=None, timeout=4):
    """
    Fetch cluster progress and node stage directly from the Assisted Installer Agent REST API.
    Returns a dict with stage info or None if the API is unreachable.
    """
    if not vm_ip:
        return None

    url = f"http://{vm_ip}:8090/api/assisted-install/v2/clusters"
    headers = {"Accept": "application/json"}
    if token:
        headers["Authorization"] = token

    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            if response.status != 200:
                return None
            clusters = json.loads(response.read().decode("utf-8"))
            if not isinstance(clusters, list) or not clusters:
                return None
            cluster = clusters[0]
            progress = cluster.get("progress", {})
            return {
                "cluster_id": cluster.get("id"),
                "status": cluster.get("status"),
                "status_info": cluster.get("status_info"),
                "total_percentage": progress.get("total_percentage", 0),
                "installing_stage_percentage": progress.get("installing_stage_percentage", 0),
                "preparing_stage_percentage": progress.get("preparing_for_installation_stage_percentage", 0),
                "hosts_count": cluster.get("total_host_count", 1),
            }
    except Exception:
        return None


def fetch_assisted_installer_host_telemetry(vm_ip, token=None, timeout=4):
    """
    Fetch granular host stage (e.g. 'Writing image to disk', 'Waiting for bootkube') from the infra-env API.
    """
    if not vm_ip:
        return None

    url = f"http://{vm_ip}:8090/api/assisted-install/v2/infra-envs"
    headers = {"Accept": "application/json"}
    if token:
        headers["Authorization"] = token

    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=timeout) as response:
            if response.status != 200:
                return None
            infra_envs = json.loads(response.read().decode("utf-8"))
            if not isinstance(infra_envs, list) or not infra_envs:
                return None
            infra_env_id = infra_envs[0].get("id")

        hosts_url = f"http://{vm_ip}:8090/api/assisted-install/v2/infra-envs/{infra_env_id}/hosts"
        req_hosts = urllib.request.Request(hosts_url, headers=headers)
        with urllib.request.urlopen(req_hosts, timeout=timeout) as response:
            if response.status != 200:
                return None
            hosts = json.loads(response.read().decode("utf-8"))
            if not isinstance(hosts, list) or not hosts:
                return None
            host = hosts[0]
            progress = host.get("progress", {})
            return {
                "current_stage": progress.get("current_stage") or host.get("status_info"),
                "stage_percentage": progress.get("installation_percentage", 0),
                "progress_info": progress.get("progress_info", ""),
                "status": host.get("status"),
                "status_info": host.get("status_info"),
            }
    except Exception:
        return None


class OpenShiftTelemetryPoller:
    """
    Asynchronous daemon thread that continuously queries the Assisted Installer Agent
    and publishes structured telemetry into the live_tracker and Celery task.
    """

    def __init__(self, vm_ip, assets_directory, on_update_callback, poll_interval=6.0):
        self.vm_ip = vm_ip
        self.assets_directory = assets_directory
        self.on_update_callback = on_update_callback
        self.poll_interval = poll_interval
        self._stop_event = threading.Event()
        self._thread = None
        self._token = None

    def start(self):
        self._thread = threading.Thread(target=self._run, daemon=True, name="OpenShiftTelemetryPoller")
        self._thread.start()

    def stop(self):
        self._stop_event.set()
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=2.0)

    def _run(self):
        while not self._stop_event.is_set():
            try:
                if not self._token:
                    self._token = extract_openshift_user_token(self.assets_directory)

                cluster_meta = fetch_assisted_installer_cluster_telemetry(self.vm_ip, self._token)
                host_meta = fetch_assisted_installer_host_telemetry(self.vm_ip, self._token)

                if cluster_meta or host_meta:
                    combined = {
                        "total_percentage": cluster_meta.get("total_percentage", 0) if cluster_meta else 0,
                        "cluster_status": cluster_meta.get("status_info") if cluster_meta else "",
                        "stage": host_meta.get("current_stage") if host_meta else "",
                        "stage_percentage": host_meta.get("stage_percentage", 0) if host_meta else 0,
                        "progress_info": host_meta.get("progress_info", "") if host_meta else "",
                    }
                    self.on_update_callback(combined)
            except Exception as exc:
                logger.debug("OpenShift telemetry poll iteration failed: %s", exc)

            self._stop_event.wait(self.poll_interval)

